const punctuation = /([?!…][?!…]*|\.{3})$/u;
const end = value => /[.!?…]$/u.test(value) ? value : value+'.';
const turn = value => value.trim().replace(/^[—–-]\s*/u,'');
const upper = value => value.charAt(0).toLocaleUpperCase('ru')+value.slice(1);
export const dialogueModes = ['Без слов автора','Слова автора после реплики','Отдельное действие после реплики','Реплика продолжается тем же предложением','После слов автора — новое предложение','Слова автора перед репликой'];
export function proseSpeech({mode, body, attribution, continuation}) {
  const first=turn(body);
  const author=attribution.trim();
  const next=turn(continuation);
  if (!first) return [];
  const dash='—\u00a0';
  const strong=punctuation.test(first);
  const beforeTag=strong?first:first.replace(/[.,;:]$/u,'')+',';
  if (!author || mode===dialogueModes[0]) return [dash+end(first)];
  if (mode===dialogueModes[5]) return [upper(author.replace(/[.!?:]+$/u,''))+':',dash+end(first)];
  if (mode===dialogueModes[2]) return [dash+end(first)+' — '+end(upper(author))];
  const tag=author.replace(/[.,;:]$/u,'');
  if (!next || mode===dialogueModes[1]) return [dash+beforeTag+' — '+end(tag)];
  if (mode===dialogueModes[3]) {
    const same=first.replace(/[.!?…,:;]+$/u,'');
    return [dash+same+', — '+tag.replace(/[.!?…]+$/u,'')+', — '+end(next)];
  }
  return [dash+beforeTag+' — '+end(tag)+' — '+end(upper(next))];
}

